// 🔥 FIXED ROUTE SUPPORT (handles /products/hufulvate)
export function findProductBySlug(slug) {
  const decoded = decodeURIComponent(slug);
  const normalized = decoded.replace(/-/g, ' ').toUpperCase();

  const brand = SLUG_TO_BRAND[normalized] || normalized;

  return PRODUCTS.find(p => p.brand.toUpperCase() === brand) || PRODUCTS[0];
}

export function findProductByBrand(brand) {
  return PRODUCTS.find(p => p.brand.toUpperCase() === brand.toUpperCase()) || PRODUCTS[0];
}